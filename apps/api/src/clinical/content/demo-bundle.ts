/** "dog bite", "bitten by a dog", "a dog bit me", "scratched by a cat"… */
function biteSynonyms(animals: string[]): string[] {
  return animals.flatMap((a) => [
    `${a} bite`,
    `${a} bit me`,
    `${a} bit`,
    `bitten by a ${a}`,
    `bitten by my ${a}`,
    `bit by a ${a}`,
    ...(a === 'snake' ? [] : [`${a} scratch`, `${a} scratched me`, `scratched by a ${a}`, `scratched by my ${a}`]),
  ]);
}

